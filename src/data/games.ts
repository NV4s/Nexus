const slugify = (value: string) =>
  value
    .toLowerCase()
    .replace(/['’]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');

const titleFromPath = (path: string) =>
  path
    .split('/')
    .pop()!
    .replace(/\.swf$/i, '')
    .replace(/^\((?:\d+|Misc)\)/, '')
    .replace(/[_-]+/g, ' ')
    .trim();

